from ucimlrepo import fetch_ucirepo

# Download dataset directly into Python
online_retail = fetch_ucirepo(id=352)

# Store data in a table
df = online_retail.data.features

# Display the first 5 rows
print("Dataset loaded successfully!")
print("Dataset size:", df.shape)
display(df.head())

import pandas as pd

# Create a copy of original data
clean_df = df.copy()

# Convert date column
clean_df["InvoiceDate"] = pd.to_datetime(
    clean_df["InvoiceDate"], errors="coerce"
)

# Remove rows without product descriptions
clean_df = clean_df.dropna(subset=["Description"])

# Remove exact duplicate rows
clean_df = clean_df.drop_duplicates()

# Display results
print("Rows before cleaning:", len(df))
print("Rows after cleaning:", len(clean_df))

print("\nMissing values:")
print(clean_df.isnull().sum())

display(clean_df.head())

import pandas as pd
import matplotlib.pyplot as plt

# Create sales value
clean_df["Sales"] = clean_df["Quantity"] * clean_df["UnitPrice"]

# Check negative quantities and prices
print("Negative quantity rows:",
      (clean_df["Quantity"] < 0).sum())

print("Zero or negative price rows:",
      (clean_df["UnitPrice"] <= 0).sum())

# Create a dataset for regular product sales
sales_df = clean_df[
    (clean_df["Quantity"] > 0) &
    (clean_df["UnitPrice"] > 0)
].copy()

print("\nRows available for sales analysis:", len(sales_df))
print("Total sales value:", round(sales_df["Sales"].sum(), 2))

# Top 10 products by quantity sold
top_products = (
    sales_df.groupby("Description")["Quantity"]
    .sum()
    .sort_values(ascending=False)
    .head(10)
)

print("\nTop 10 products by quantity sold:")
display(top_products.reset_index())

# Plot top products
top_products.sort_values().plot(kind="barh", figsize=(10, 6))
plt.title("Top 10 Products by Quantity Sold")
plt.xlabel("Quantity Sold")
plt.ylabel("Product")
plt.tight_layout()
plt.show()

# Step 4: Monthly Sales Analysis

# Extract month from invoice date
sales_df["Month"] = (
    sales_df["InvoiceDate"].dt.to_period("M").astype(str)
)

# Calculate monthly sales
monthly_sales = (
    sales_df.groupby("Month")["Sales"]
    .sum()
    .sort_index()
)

print("Monthly Sales Summary:")
display(monthly_sales.reset_index())

# Plot monthly sales chart
import matplotlib.pyplot as plt

plt.figure(figsize=(12, 6))
monthly_sales.plot(kind="line", marker="o")

plt.title("Monthly Sales Trend")
plt.xlabel("Month")
plt.ylabel("Sales Value")
plt.xticks(rotation=45)
plt.grid(True)
plt.tight_layout()
plt.show()

# Country-wise Sales Analysis

country_sales = (
    sales_df.groupby("Country")["Sales"]
    .sum()
    .sort_values(ascending=False)
    .head(10)
)

print("Top 10 Countries by Sales Value:")
display(country_sales.reset_index())

# Create a chart
import matplotlib.pyplot as plt

plt.figure(figsize=(10, 6))
country_sales.sort_values().plot(kind="barh")

plt.title("Top 10 Countries by Sales Value")
plt.xlabel("Sales Value")
plt.ylabel("Country")
plt.tight_layout()
plt.show()

